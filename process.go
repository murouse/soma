package soma

import "context"

// Process определяет контракт компонента, управляемого фреймворком Soma.
// Компоненты жизненного цикла должны реализовывать этот интерфейс для обеспечения
// корректного запуска и плавного завершения работы (Graceful Shutdown).
type Process interface {
	// Prepare выполняет предварительную инициализацию (валидация конфигурации,
	// открытие соединений, регистрация в реестрах).
	// Метод вызывается последовательно для всех процессов до фазы Run.
	// Если метод возвращает ошибку, запуск приложения прерывается: для уже подготовленных
	// процессов вызывается Shutdown, а для самого упавшего — нет. Поэтому при ошибке
	// Prepare обязан сам освободить то, что успел захватить.
	Prepare(ctx context.Context) error

	// Run запускает основной цикл работы компонента. Требования к реализации:
	// 1. Блокировка: Метод должен блокировать выполнение до тех пор, пока процесс
	//    не завершится штатно или по сигналу остановки.
	// 2. Реакция на остановку: Компонент должен завершить работу, если произойдет
	//    одно из событий:
	//    - Контекст ctx был отменен (ctx.Done()).
	//    - Внешнее воздействие, вызванное методом Shutdown (например, закрытие
	//      слушающего сокета сервером).
	// 3. Обработка ошибок: Если метод возвращает ошибку (отличную от context.Canceled),
	//    она трактуется как критическая, что инициирует немедленную остановку всех остальных процессов.
	// 4. Штатное завершение: возврат nil не останавливает остальные процессы. Когда все
	//    процессы завершились, приложение переходит к остановке.
	Run(ctx context.Context) error

	// Shutdown выполняет плавное завершение работы компонента. Требования к реализации:
	// 1. Разблокировка Run: Если метод Run заблокирован на ожидании сетевых событий
	//    (например, http.ListenAndServe), Shutdown ОБЯЗАН совершить действие,
	//    которое разблокирует Run (например, вызов server.Shutdown или закрытие listener).
	// 2. Использование контекста: Метод должен уважать переданный shutdownCtx
	//    (учитывать таймаут) при выполнении операций завершения.
	// 3. Безопасность: Метод должен корректно закрыть все открытые ресурсы (соединения,
	//    файлы), не допуская утечек памяти или повреждения данных.
	// 4. Вызов без Run: Shutdown может быть вызван после успешного Prepare, но до (или вместо)
	//    Run — при ошибке Prepare другого процесса или раннем сигнале. Это нужно обрабатывать
	//    корректно, а Run, вызванный после Shutdown, должен сразу завершаться.
	Shutdown(ctx context.Context) error
}

// Named — опциональный интерфейс процесса. Если процесс его реализует, Name используется
// в логах и ошибках вместо имени типа.
type Named interface {
	Name() string
}

// Drainer — опциональный интерфейс процесса. Drain вызывается в начале остановки, до паузы
// WithShutdownDelay и до Shutdown: процесс перестает сообщать о готовности (например, health
// переходит в NOT_SERVING), но продолжает обслуживать запросы. Должен быть быстрым и неблокирующим.
type Drainer interface {
	Drain()
}
